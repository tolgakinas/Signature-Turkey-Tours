export const STORAGE_KEY_REVIEWS = 'signature_turkey_reviews_v1';

export function getStoredReviews(): TravelerReview[] {
  if (typeof window === 'undefined') return REVIEWS_DATA;
  try {
    const data = localStorage.getItem(STORAGE_KEY_REVIEWS);
    if (!data) {
      localStorage.setItem(STORAGE_KEY_REVIEWS, JSON.stringify(REVIEWS_DATA));
      return REVIEWS_DATA;
    }
    return JSON.parse(data);
  } catch {
    return REVIEWS_DATA;
  }
}

export function saveStoredReviews(reviews: TravelerReview[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY_REVIEWS, JSON.stringify(reviews));
  } catch (err) {
    console.error('Failed to save reviews to localStorage', err);
  }
}
